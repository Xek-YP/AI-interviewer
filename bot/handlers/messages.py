def format_interview_count(count: int) -> str:
    """Склоняет слово «собеседование» по числу."""
    n = abs(count) % 100
    n1 = n % 10
    if 11 <= n <= 14:
        word = 'собеседований'
    elif n1 == 1:
        word = 'собеседование'
    elif 2 <= n1 <= 4:
        word = 'собеседования'
    else:
        word = 'собеседований'
    return f'{count} {word}'


def build_onboarding_message(tariff_block: str) -> str:
    """Первый экран: ценность продукта и отличие бесплатного тарифа от Premium."""
    return (
        '🤖 AI-Собеседование\n\n'
        'Пройди полноценное техническое собеседование\n'
        'с AI-интервьюером.\n\n'
        '• Python / Backend\n'
        '• Junior / Middle / Senior\n'
        '• Персональные вопросы по вакансии\n'
        '• Оценка каждого ответа\n'
        '• Итоговый балл и разбор ошибок\n\n'
        f'{tariff_block}'
    )


def build_free_tariff_block(price_label: str, free_limit: int) -> str:
    """Строка бесплатного лимита и цены Premium."""
    free_label = format_interview_count(free_limit)
    return (
        f'🎁 Бесплатно: {free_label} в месяц\n'
        f'💎 Premium: безлимит — {price_label} / месяц'
    )


def build_premium_tariff_block(expires_label: str) -> str:
    """Строка для пользователя с уже активным Premium."""
    return f'💎 Premium активен до {expires_label} — безлимит'


